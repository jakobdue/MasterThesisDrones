import matplotlib.pyplot as plt
from mpl_toolkits.mplot3d import Axes3D

def plot_sequences_3d(seq_dict, title):
    fig = plt.figure(figsize=(7,7))
    ax = fig.add_subplot(111, projection='3d')

    colors = ['red', 'blue', 'green', 'orange']

    for i, (key, path) in enumerate(seq_dict.items()):
        xs = [p[0] for p in path]
        ys = [p[1] for p in path]
        zs = [p[2] for p in path]

        ax.scatter(xs, ys, zs, s=200, color=colors[i], label=f"Drone {key}")

        for j, (x, y, z) in enumerate(zip(xs, ys, zs)):
            ax.text(x, y, z, str(j))

    ax.set_xlabel("x")
    ax.set_ylabel("y")
    ax.set_zlabel("z")
    ax.set_title(title)
    ax.legend()

    plt.show()


plot_sequences_3d(sequences, "Patrol mission")
